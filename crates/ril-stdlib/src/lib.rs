//! Versioned Ril sources. The compiler parses and checks these ordinary modules.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

pub struct Module {
    pub path: &'static str,
    pub namespace: &'static str,
    pub source: &'static str,
    pub private: bool,
    pub representations: &'static [Representation],
}

/// An opaque declaration and the ordinary private type implementing its data.
/// The compiler resolves both names to declaration IDs in this module.
pub struct Representation {
    pub opaque: &'static str,
    pub implementation: &'static str,
}

